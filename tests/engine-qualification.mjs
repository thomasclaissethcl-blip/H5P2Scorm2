import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx=vm.createContext({});ctx.globalThis=ctx;
vm.runInContext(fs.readFileSync('src/engine-qualification.js','utf8'),ctx);
const q=ctx.H5PConverterModules.engineQualification;
const profile={id:'h5p-standalone-3.8.0-candidate',playerVersion:'3.8.0',status:'candidate'};
const analysis={h5pJson:{title:'Essai Game Map',mainLibrary:'H5P.GameMap'},libraries:[{library:{machineName:'H5P.GameMap',majorVersion:1,minorVersion:9,patchVersion:8}}]};
const test=q.newSession({profile,analysis,file:{name:'map.h5p',size:1234},browser:'Firefox',clock:()=> '2026-10-27T14:00:00Z'});
assert.equal(test.report().evaluation,'essai_incomplet');
assert.equal(test.report().qualification,'non_qualifie');
assert.equal(test.report().observations.ready,0);
assert.equal(test.mark('load','reussi'),true);
assert.equal(test.mark('render','echoue'),true);
assert.equal(test.mark('bogus','reussi'),false);
assert.equal(test.mark('media','qualified'),false);
test.record({type:'ready',message:'OK'});test.record({type:'xapi',message:'Score personnel 3/5'});
test.record({type:'resource-blocked',message:'ressource refusée'});
test.record({type:'error',message:'erreur du lecteur'});
test.setNote('Hotspots flous');
let r=JSON.parse(JSON.stringify(test.report()));
assert.equal(r.observations.ready,1);
assert.equal(r.observations.xapi,1);
assert.equal(r.observations.error,1);
assert.equal(r.observations.errors.length,2);
assert.equal(r.summary.failure,1);
assert.equal(r.evaluation,'anomalies_constatees');
assert.equal(r.exportAllowedByThisReport,false);
assert.equal(r.activity.libraries[0].version.join('.'),'1.9.8');
assert.ok(!JSON.stringify(r).includes('Score personnel'));
for (const c of q.criteria) test.mark(c.id,'reussi');
r=test.report();
assert.equal(r.evaluation,'essai_documente_non_qualifie');
assert.equal(r.qualification,'non_qualifie');
assert.equal(r.summary.success,q.criteria.length);
assert.equal(r.summary.notTested,0);
const other=q.newSession({profile:{id:'h5p-standalone-3.8.2',playerVersion:'3.8.2',status:'reference'},analysis,file:{name:'other.h5p',size:7},browser:'Chrome'});
assert.equal(other.report().summary.notTested,q.criteria.length);
console.log('Lot 4.3 : suivi des preuves, statut non qualifié, confidentialité et sessions indépendantes OK');
