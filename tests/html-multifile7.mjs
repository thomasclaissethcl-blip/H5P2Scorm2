import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({console});context.globalThis=context;
vm.runInContext(fs.readFileSync('src/html-multifile.js','utf8'),context);
const m=context.H5PConverterModules.htmlMultifile;
assert.ok(m);
const html=m.indexHtml({title:'Livre <H5P> & "Moodle"',language:'fr'});
assert.ok(html.includes('Livre &lt;H5P&gt; &amp; &quot;Moodle&quot;'));
assert.ok(html.includes('src="./player/main.bundle.js"'));
assert.ok(html.includes('src="./html/player-init.js"'));
assert.ok(html.includes('id="h5p-container"'));
for(const forbidden of ['imsmanifest.xml','scorm12.js','SCORM12','https://','http://','//cdn','<base'])assert.ok(!html.includes(forbidden),`HTML contient ${forbidden}`);
const js=m.bootstrapSource({language:'fr',translations:{H5P:{fullscreen:'Plein écran'}}});
new vm.Script(js);
assert.ok(js.includes("h5pJsonPath:'./h5p'"));
assert.ok(js.includes("contentJsonPath:'./h5p/content'"));
assert.ok(js.includes("librariesPath:'./h5p'"));
assert.ok(js.includes("frameJs:'./player/frame.bundle.js'"));
assert.ok(js.includes("frameCss:'./player/styles/h5p.css'"));
assert.ok(js.includes("customCss:['./custom/custom.css']"));
assert.ok(!/SCORM12|cmi\.|LMSInitialize|LMSSetValue/.test(js));
let didRun=false; const nodes={'h5p-container':{},'runtime-error':{textContent:''}};
const listeners={};const calls=[];
const inner=vm.createContext({console,document:{documentElement:{lang:'',dataset:{}},getElementById:id=>nodes[id]},
  H5PStandalone:{H5P:class{constructor(el,options){calls.push({el,options});didRun=true;}}}});
inner.window=inner;inner.addEventListener=(name,fn)=>{listeners[name]=fn};
vm.runInContext(js,inner);
assert.equal(typeof listeners.DOMContentLoaded,'function');
await listeners.DOMContentLoaded();
assert.ok(didRun);
assert.equal(calls[0].el,nodes['h5p-container']);
assert.equal(calls[0].options.h5pJsonPath,'./h5p');
assert.equal(calls[0].options.translations.H5P.fullscreen,'Plein écran');
assert.equal(inner.document.documentElement.dataset.h5pHtmlStatus,'ready');
const errctx=vm.createContext({console,document:{documentElement:{lang:'',dataset:{}},getElementById:id=>nodes[id]}});
const errlist={};errctx.window=errctx;errctx.addEventListener=(name,fn)=>errlist[name]=fn;
vm.runInContext(js,errctx);
await errlist.DOMContentLoaded();
assert.equal(errctx.document.documentElement.dataset.h5pHtmlStatus,'error');
assert.match(nodes['runtime-error'].textContent,/lecteur H5P local/);
const report=JSON.parse(JSON.stringify(m.generationReport({title:'Test',language:'fr',mainLibrary:'H5P.GameMap',
  libraries:[{key:'H5P.GameMap 1.9',folder:'H5P.GameMap-1.9'}],profileId:'fixed',playerVersion:'3.8.2',coreApi:{majorVersion:1,minorVersion:28},localization:{replaced:1},cssLength:45})));
assert.equal(report.format,'html-multifile');
assert.equal(report.portability.cdnRequiredAtRuntime,false);
assert.equal(report.portability.paths,'relative-to-index');
assert.equal(report.parameters.scormBridge,false);
assert.equal(report.libraries.length,1);
assert.ok(m.readme({title:'Test',language:'fr',playerVersion:'3.8.2'}).includes('index.html'));
console.log('Lot 7 : lanceur HTML autonome, chemins relatifs, CSP hote, CSS, traduction et rapport : OK');
