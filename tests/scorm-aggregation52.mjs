import fs from 'node:fs';import vm from 'node:vm';import assert from 'node:assert/strict';
const ctx=vm.createContext({});vm.runInContext(fs.readFileSync('src/scorm-scoring.js','utf8'),ctx);
const make=ctx.H5PConverterModules.scoring.createTracker;
const q1='11111111-1111-4111-8111-111111111111',q2='22222222-2222-4222-8222-222222222222';
const evt=(id,verb,score,child,complete=false,registration='attempt-1')=>({id,verb:{id:'http://adlnet.gov/expapi/verbs/'+verb},object:{id:child?'http://h?subContentId='+child:'http://h',definition:{extensions:child?{'http://h5p.org/x-api/h5p-subContentId':child}:{}}},context:{registration,contextActivities:child?{parent:[{id:'http://h'}]}:{}},result:{...(score?{score}:{}),...(complete?{completion:true}:{})}});
const opts={mainLibrary:'H5P.InteractiveBook',expectedSubContentIds:[q1,q2]};
const t=make(opts);
assert.equal(t.ingest(evt('a','answered',{raw:4,max:5},q1)).kind,'subcontent');
assert.equal(t.ingest(evt('c','completed',null,null,true)).kind,'root-final-unscored');
assert.equal(t.ingest(evt('b','answered',{raw:6,max:10},q2)).kind,'aggregate');
assert.equal(Math.round(t.summary().observedScores.reduce((x,y)=>x+y.raw,0)),10);
const snapshot=t.snapshot();assert.equal(snapshot.rows.length,2);
const restored=make(opts);assert.equal(restored.restore(JSON.parse(JSON.stringify(snapshot))),true);
assert.equal(restored.ingest(evt('later','completed',null,null,true)).kind,'aggregate');
assert.equal(restored.ingest(evt('update','answered',{raw:3,max:5},q1)).percent,60);
const alternate=make({mainLibrary:'H5P.InteractiveBook',expectedSubContentIds:[q1]});
assert.equal(alternate.restore(snapshot),false);
const corrupted={...snapshot,rows:[{id:q1,raw:99,min:0,max:1,final:true}]};
assert.equal(make(opts).restore(corrupted),false);
const native=make(opts);native.ingest(evt('a','answered',{raw:4,max:5},q1));
native.ingest(evt('b','answered',{raw:6,max:10},q2));
assert.equal(native.ingest(evt('n','completed',{raw:9,max:10},null,true)).percent,90);
assert.equal(native.ingest(evt('again','completed',null,null,true)).reason,'native-final-already-authoritative');
assert.equal(t.ingest(evt('new','answered',{raw:2,max:5},q1,false,'attempt-2')).kind,'subcontent');
assert.equal(t.summary().rootFinal,false);
assert.equal(t.ingest(evt('end','completed',null,null,true,'attempt-2')).kind,'root-final-unscored');
const foreign=make(opts);foreign.ingest(evt('one','answered',{raw:4,max:5},q1));
foreign.ingest(evt('two','answered',{raw:6,max:10},q2));
assert.equal(foreign.ingest(evt('extra','answered',{raw:1,max:1},'33333333-3333-4333-8333-333333333333')).reason,'unplanned-scored-child');
assert.equal(foreign.ingest(evt('done','completed',null,null,true)).kind,'root-final-unscored');
assert.equal(foreign.summary().unplannedScored,true);
assert.equal(make(opts).restore(foreign.snapshot()),true);
console.log('Agrégation conditionnelle et reprise du registre : score final, doublons, priorite native, tentative OK');
